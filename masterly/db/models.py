"""The 14 tables of ``docs/design/co-so-du-lieu.md``.

Identifiers are UUIDs generated by the application. Deleting an account removes
everything it owns; references kept only for context (a session's learning path,
the session an assessment or note came from) are cleared instead.
"""

from __future__ import annotations

from datetime import datetime
import uuid

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    Computed,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    LargeBinary,
    MetaData,
    Text,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def _id() -> Mapped[uuid.UUID]:
    return mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)


def _fk(target: str, *, ondelete: str = "CASCADE", nullable: bool = False) -> Mapped:
    return mapped_column(
        UUID(as_uuid=True), ForeignKey(target, ondelete=ondelete), nullable=nullable, index=True
    )


def _created() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now())


def _updated() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())


def _empty_object() -> Mapped[dict]:
    return mapped_column(JSONB, server_default=text("'{}'::jsonb"))


# --- Groups and accounts ---------------------------------------------------


class Group(Base):
    """One group, created when its owner registers; holds the group's service config."""

    __tablename__ = "groups"

    id: Mapped[uuid.UUID] = _id()
    model_catalog: Mapped[dict] = _empty_object()
    catalog_revision: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    codex_session: Mapped[bytes | None] = mapped_column(LargeBinary)
    created_at: Mapped[datetime] = _created()


class Account(Base):
    """Every account: the group owner and the learners the owner created."""

    __tablename__ = "accounts"
    __table_args__ = (
        CheckConstraint("role IN ('owner', 'learner')", name="role"),
        CheckConstraint("theme IN ('light', 'dark')", name="theme"),
        CheckConstraint("language IN ('vi', 'en')", name="language"),
        Index("uq_accounts_email", func.lower(text("email")), unique=True),
        Index(
            "uq_accounts_group_owner",
            "group_id",
            unique=True,
            postgresql_where=text("role = 'owner'"),
        ),
    )

    id: Mapped[uuid.UUID] = _id()
    group_id: Mapped[uuid.UUID] = _fk("groups.id")
    role: Mapped[str] = mapped_column(Text)
    email: Mapped[str] = mapped_column(Text)
    password_hash: Mapped[str] = mapped_column(Text)
    display_name: Mapped[str] = mapped_column(Text, server_default="")
    avatar: Mapped[str] = mapped_column(Text, server_default="")
    theme: Mapped[str] = mapped_column(Text, server_default="light")
    language: Mapped[str] = mapped_column(Text, server_default="vi")
    disabled: Mapped[bool] = mapped_column(server_default=text("false"))
    created_at: Mapped[datetime] = _created()


# --- Per account -----------------------------------------------------------


class Workspace(Base):
    __tablename__ = "workspaces"
    __table_args__ = (
        Index(
            "uq_workspaces_account_default",
            "account_id",
            unique=True,
            postgresql_where=text("is_default"),
        ),
    )

    id: Mapped[uuid.UUID] = _id()
    account_id: Mapped[uuid.UUID] = _fk("accounts.id")
    name: Mapped[str] = mapped_column(Text)
    is_default: Mapped[bool] = mapped_column(server_default=text("false"))
    archived_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = _created()


class Memory(Base):
    """One part of a learner's memory, as a Markdown document."""

    __tablename__ = "memories"

    account_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("accounts.id", ondelete="CASCADE"), primary_key=True
    )
    slot: Mapped[str] = mapped_column(Text, primary_key=True)
    content: Mapped[str] = mapped_column(Text, server_default="")
    updated_at: Mapped[datetime] = _updated()


# --- Conversations ---------------------------------------------------------


class Session(Base):
    __tablename__ = "sessions"

    id: Mapped[uuid.UUID] = _id()
    workspace_id: Mapped[uuid.UUID] = _fk("workspaces.id")
    path_id: Mapped[uuid.UUID | None] = _fk(
        "learning_paths.id", ondelete="SET NULL", nullable=True
    )
    title: Mapped[str] = mapped_column(Text, server_default="")
    summary: Mapped[dict] = _empty_object()
    preferences: Mapped[dict] = _empty_object()
    archived_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = _created()
    updated_at: Mapped[datetime] = _updated()


class Message(Base):
    __tablename__ = "messages"
    __table_args__ = (CheckConstraint("role IN ('user', 'assistant')", name="role"),)

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    session_id: Mapped[uuid.UUID] = _fk("sessions.id")
    parent_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("messages.id", ondelete="SET NULL"), index=True
    )
    role: Mapped[str] = mapped_column(Text)
    content: Mapped[str] = mapped_column(Text, server_default="")
    extra: Mapped[dict] = _empty_object()
    created_at: Mapped[datetime] = _created()


class Turn(Base):
    __tablename__ = "turns"
    __table_args__ = (
        CheckConstraint(
            "status IN ('running', 'completed', 'failed', 'cancelled')", name="status"
        ),
    )

    id: Mapped[uuid.UUID] = _id()
    session_id: Mapped[uuid.UUID] = _fk("sessions.id")
    message_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("messages.id", ondelete="SET NULL"), index=True
    )
    status: Mapped[str] = mapped_column(Text, server_default="running")
    error: Mapped[str] = mapped_column(Text, server_default="")
    created_at: Mapped[datetime] = _created()
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class TurnEvent(Base):
    __tablename__ = "turn_events"

    turn_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("turns.id", ondelete="CASCADE"), primary_key=True
    )
    seq: Mapped[int] = mapped_column(Integer, primary_key=True)
    type: Mapped[str] = mapped_column(Text)
    data: Mapped[dict] = _empty_object()
    created_at: Mapped[datetime] = _created()


# --- Learning paths --------------------------------------------------------


class LearningPath(Base):
    __tablename__ = "learning_paths"
    __table_args__ = (CheckConstraint("status IN ('active', 'archived')", name="status"),)

    id: Mapped[uuid.UUID] = _id()
    workspace_id: Mapped[uuid.UUID] = _fk("workspaces.id")
    goal: Mapped[str] = mapped_column(Text, server_default="")
    status: Mapped[str] = mapped_column(Text, server_default="active")
    state: Mapped[dict] = _empty_object()
    revision: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    created_at: Mapped[datetime] = _created()
    updated_at: Mapped[datetime] = _updated()


class Assessment(Base):
    """One graded answer; the evidence mastery and the review schedule are computed from."""

    __tablename__ = "assessments"
    __table_args__ = (
        CheckConstraint("kind IN ('quiz', 'qualitative', 'review')", name="kind"),
        CheckConstraint("result IN ('correct', 'incorrect', 'partial')", name="result"),
        Index("ix_assessments_path_point", "path_id", "knowledge_point_id", "created_at"),
    )

    id: Mapped[uuid.UUID] = _id()
    path_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("learning_paths.id", ondelete="CASCADE")
    )
    knowledge_point_id: Mapped[str] = mapped_column(Text)
    session_id: Mapped[uuid.UUID | None] = _fk("sessions.id", ondelete="SET NULL", nullable=True)
    kind: Mapped[str] = mapped_column(Text)
    result: Mapped[str] = mapped_column(Text)
    question: Mapped[dict] = _empty_object()
    detail: Mapped[dict] = _empty_object()
    created_at: Mapped[datetime] = _created()


# --- Documents -------------------------------------------------------------


class KnowledgeBase(Base):
    __tablename__ = "knowledge_bases"

    id: Mapped[uuid.UUID] = _id()
    workspace_id: Mapped[uuid.UUID] = _fk("workspaces.id")
    name: Mapped[str] = mapped_column(Text)
    embedding_model: Mapped[str] = mapped_column(Text, server_default="")
    created_at: Mapped[datetime] = _created()


class Document(Base):
    __tablename__ = "documents"
    __table_args__ = (
        CheckConstraint("status IN ('processing', 'ready', 'failed')", name="status"),
    )

    id: Mapped[uuid.UUID] = _id()
    knowledge_base_id: Mapped[uuid.UUID] = _fk("knowledge_bases.id")
    folder: Mapped[str] = mapped_column(Text, server_default="")
    file_name: Mapped[str] = mapped_column(Text)
    storage_key: Mapped[str] = mapped_column(Text)
    size_bytes: Mapped[int] = mapped_column(BigInteger)
    status: Mapped[str] = mapped_column(Text, server_default="processing")
    error: Mapped[str] = mapped_column(Text, server_default="")
    created_at: Mapped[datetime] = _created()


class Chunk(Base):
    __tablename__ = "chunks"
    __table_args__ = (
        Index("ix_chunks_document_ordinal", "document_id", "ordinal"),
        Index("ix_chunks_search_text", "search_text", postgresql_using="gin"),
    )

    id: Mapped[uuid.UUID] = _id()
    document_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("documents.id", ondelete="CASCADE")
    )
    ordinal: Mapped[int] = mapped_column(Integer)
    content: Mapped[str] = mapped_column(Text)
    locator: Mapped[dict] = _empty_object()
    # The dimension depends on the group's embedding model, so it is not fixed
    # here; the similarity index is added with the document feature.
    embedding: Mapped[list[float] | None] = mapped_column(Vector())
    search_text: Mapped[str | None] = mapped_column(
        TSVECTOR, Computed("to_tsvector('simple', content)", persisted=True)
    )


# --- Notes -----------------------------------------------------------------


class Note(Base):
    __tablename__ = "notes"

    id: Mapped[uuid.UUID] = _id()
    workspace_id: Mapped[uuid.UUID] = _fk("workspaces.id")
    session_id: Mapped[uuid.UUID | None] = _fk("sessions.id", ondelete="SET NULL", nullable=True)
    title: Mapped[str] = mapped_column(Text, server_default="")
    content: Mapped[str] = mapped_column(Text, server_default="")
    created_at: Mapped[datetime] = _created()
    updated_at: Mapped[datetime] = _updated()
